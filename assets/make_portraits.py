"""Convert the included transparent sprite strip to the board's RGB565 format."""

from pathlib import Path

from PIL import Image


HERE = Path(__file__).resolve().parent
SIZE = (136, 116)
FRAMES = ("Idle", "Blink", "Smile", "Wave", "Annoyed", "Sleep",
          "Dizzy", "Curious", "Sad", "Think", "Talk")
KEY = 0xF81F


def rgb565(pixel):
    r, g, b, a = pixel
    if a < 112:
        return KEY
    value = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
    return value if value != KEY else KEY - 1


def display_order(rgb565_value):
    # M5GFX's 16-bit canvas expects the most significant byte first.
    return ((rgb565_value & 0xFF) << 8) | (rgb565_value >> 8)


def main():
    width, height = SIZE
    with Image.open(HERE / "whale.png") as source:
        atlas = source.convert("RGBA")
    if atlas.size != (width * len(FRAMES), height):
        raise ValueError("Wrong sprite strip dimensions")
    lines = [
        "// Generated by assets/make_portraits.py. See assets/NOTICE.md.",
        "#pragma once",
        "#include <M5GFX.h>",
        "namespace portraits {",
        f"constexpr int Width = {width};",
        f"constexpr int Height = {height};",
        "// The pixels and transparent color use the canvas's byte-swapped RGB565.",
        f"constexpr lgfx::swap565_t Key = uint16_t{{0x{display_order(KEY):04x}}};",
        "enum Frame { " + ", ".join(FRAMES) + " };",
        "constexpr lgfx::swap565_t Pixels[][Width * Height] = {",
    ]
    for index in range(len(FRAMES)):
        x = index * width
        frame = atlas.crop((x, 0, x + width, height))
        pixels = [frame.getpixel((xx, yy)) for yy in range(height) for xx in range(width)]
        lines.append("    {")
        for offset in range(0, len(pixels), 20):
            lines.append("        " + ", ".join(
                f"0x{display_order(rgb565(pixel)):04x}" for pixel in pixels[offset:offset + 20]
            ) + ",")
        lines.append("    },")
    lines.extend(("};", "}", ""))
    (HERE.parent / "WhaleMate" / "Portraits.h").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
